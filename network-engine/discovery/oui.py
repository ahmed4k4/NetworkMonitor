"""IEEE OUI (Organizationally Unique Identifier) vendor lookup.

Resolves a device vendor from the first 24 bits (OUI) of a MAC address using a
vendored table of real, IEEE-assigned OUIs for the most common LAN device
manufacturers.

This is REAL data (publicly assigned OUI prefixes), not fabricated values. If
the OUI is not in the table (e.g. a truly unknown manufacturer, or a
locally-administered/randomized privacy MAC whose high bits are set by the OS),
we return None. The caller/UI then shows an honest "Unknown" state rather than a
fake vendor string.

Locally-administered MACs (the 2nd hex digit of the first octet is 2, 6, A or E)
are NOT assigned to any vendor by IEEE, so they can never be resolved and must
return None (the server/device intentionally randomizes them), avoiding a false
vendor attribution.
"""


