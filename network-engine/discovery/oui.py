def _normalize_oui(mac: str):
    """Return the lowercase, no-separator 3-byte OUI prefix of a MAC address.

    Accepts "AA:BB:CC" and "AA-BB-CC" and "AABBCCDDEEFF" forms. Returns None if
    the MAC is malformed.
    """
    if not mac:
        return None
    hex_digits = "".join(ch for ch in str(mac).upper() if ch in "0123456789ABCDEF")
    if len(hex_digits) < 6:
        return None
    return hex_digits[:6].lower()


def is_locally_administered(mac: str) -> bool:
    """True if the MAC carries the locally-administered (randomized) bit.

    Privacy MACs set the LSB of the first octet; these are generated by the OS
    and are NOT assigned to any vendor, so an OUI lookup is meaningless.
    """
    hex_digits = "".join(ch for ch in str(mac).upper() if ch in "0123456789ABCDEF")
    if len(hex_digits) < 2:
        return False
    try:
        first_octet = int(hex_digits[:2], 16)
    except ValueError:
        return False
    return bool(first_octet & 0x02)


def lookup_vendor(mac: str):
    """Return the vendor name for a MAC address, or None if unknown.

    Never fabricates a value: returns None for unknown OUIs and for
    locally-administered (randomized) MACs.
    """
    if not mac:
        return None

    # Do not attempt to attribute a randomized privacy MAC to a vendor.
    if is_locally_administered(mac):
        return None

    oui = _normalize_oui(mac)
    if oui is None:
        return None

    return _OUI_MAP.get(oui)