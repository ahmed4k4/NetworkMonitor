function DropdownMenuContent({
  align = "start",
  alignOffset = 0,
  side = "bottom",
  sideOffset = 4,
  className,
  ...props
}: MenuPrimitive.Popup.Props &
  Pick<
    MenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  >) {
  const contentRef = React.useRef<HTMLDivElement>(null)

  // Handle keyboard navigation within the dropdown
  React.useEffect(() => {
    if (!contentRef.current) return

    const handleKeyDown = (event: KeyboardEvent) => {
      const items = contentRef.current?.querySelectorAll<HTMLElement>(
        '[data-slot="dropdown-menu-item"], [data-slot="dropdown-menu-checkbox-item"], [data-slot="dropdown-menu-radio-item"], [data-slot="dropdown-menu-sub-trigger"]'
      )
      
      if (!items || items.length === 0) return

      const currentIndex = Array.from(items).findIndex(item => item === document.activeElement)
      let nextIndex = currentIndex

      switch (event.key) {
        case "ArrowDown":
          event.preventDefault()
          nextIndex = (currentIndex + 1) % items.length
          items[nextIndex]?.focus()
          break
        case "ArrowUp":
          event.preventDefault()
          nextIndex = (currentIndex - 1 + items.length) % items.length
          items[nextIndex]?.focus()
          break
        case "Home":
          event.preventDefault()
          items[0]?.focus()
          break
        case "End":
          event.preventDefault()
          items[items.length - 1]?.focus()
          break
        case "Escape":
          event.preventDefault()
          // Close the menu - trigger will handle this
          const trigger = document.querySelector('[data-slot="dropdown-menu-trigger"]') as HTMLElement
          trigger?.focus()
          break
        case "Tab":
          // Allow tab to close the menu
          break
        default:
          break
      }
    }

    contentRef.current.addEventListener("keydown", handleKeyDown)
    return () => contentRef.current?.removeEventListener("keydown", handleKeyDown)
  }, [])

  // Focus first item when menu opens (using MutationObserver to detect when menu becomes visible)
  React.useEffect(() => {
    if (!contentRef.current) return

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "attributes" && mutation.attributeName === "data-open") {
          const target = mutation.target as HTMLElement
          if (target.dataset.open === "true") {
            const firstItem = contentRef.current?.querySelector<HTMLElement>(
              '[data-slot="dropdown-menu-item"], [data-slot="dropdown-menu-checkbox-item"], [data-slot="dropdown-menu-radio-item"], [data-slot="dropdown-menu-sub-trigger"]'
            )
            firstItem?.focus()
          }
        }
      }
    })

    observer.observe(contentRef.current, { attributes: true, attributeFilter: ["data-open"] })
    return () => observer.disconnect()
  }, [])

  return (
    <MenuPrimitive.Portal>
      <MenuPrimitive.Positioner
        className="isolate z-50 outline-none"
        align={align}
        alignOffset={alignOffset}
        side={side}
        sideOffset={sideOffset}
      >
        <MenuPrimitive.Popup
          ref={contentRef}
          data-slot="dropdown-menu-content"
          className={cn("z-50 max-h-(--available-height) w-(--anchor-width) min-w-32 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-popover p-1 text-popover-foreground shadow-md ring-1 ring-foreground/10 duration-150 outline-none data-[side=bottom]:slide-in-from-top-2 data-[side=inline-end]:slide-in-from-left-2 data-[side=inline-start]:slide-in-from-right-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:overflow-hidden data-closed:fade-out-0 data-closed:zoom-out-95", className )}
          tabIndex={-1}
          role="menu"
          {...props}
        />
      </MenuPrimitive.Positioner>
    </MenuPrimitive.Portal>
  )
}

